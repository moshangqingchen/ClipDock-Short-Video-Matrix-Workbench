// Code-drawn UI asset: blue clapperboard, matching the workbench navigation mark.
import { deflateSync } from "node:zlib";
import fs from "node:fs";
const size = 64;
const pixels = Buffer.alloc((size * 4 + 1) * size);
for (let y = 0; y < size; y++)
  for (let x = 0; x < size; x++) {
    const u = (x + 0.5) / 2,
      v = (y + 0.5) / 2;
    const dx = Math.max(7 - u, 0, u - 25),
      dy = Math.max(7 - v, 0, v - 25);
    if (dx * dx + dy * dy > 25 || u < 2 || u > 30 || v < 2 || v > 30) continue;
    const at = y * (size * 4 + 1) + 1 + x * 4;
    const border = u >= 7 && u <= 25 && v >= 13 && v <= 25 && (u < 9 || u > 23 || v > 23 || v < 15);
    const lid = u >= 7 && u <= 25 && v >= 7 && v <= 12 && (u + v) % 7 < 3;
    const play = u >= 13 && u <= 19 && Math.abs(v - 19) <= (19 - u) * 0.58;
    pixels.set(border || lid || play ? [255, 255, 255, 255] : [28, 93, 236, 255], at);
  }
function chunk(type, data) {
  const bytes = Buffer.concat([Buffer.from(type), data]);
  let crc = 0xffffffff;
  for (const byte of bytes) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0);
  }
  const length = Buffer.alloc(4),
    checksum = Buffer.alloc(4);
  length.writeUInt32BE(data.length);
  checksum.writeUInt32BE((crc ^ 0xffffffff) >>> 0);
  return Buffer.concat([length, bytes, checksum]);
}
const header = Buffer.alloc(13);
header.writeUInt32BE(size);
header.writeUInt32BE(size, 4);
header[8] = 8;
header[9] = 6;
const png = Buffer.concat([
  Buffer.from("89504e470d0a1a0a", "hex"),
  chunk("IHDR", header),
  chunk("IDAT", deflateSync(pixels)),
  chunk("IEND", Buffer.alloc(0)),
]);
fs.writeFileSync(
  "src/main/window/tray-icon.ts",
  `// Generated by scripts/generate-tray-icon.mjs; bundled without external asset paths.\nexport const trayIconPng = "${png.toString("base64")}";\n`,
);
